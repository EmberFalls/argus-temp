from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages/shared/src"))

from argus_contracts import models  # noqa: E402


CONTRACT_NAMES = [
    "SpecClaim", "SpecEntity", "ValidationRule", "Step", "TestCase", "Spec", "BindingResult",
    "ElementCatalogEntry", "AppGraphNode", "AppGraphEdge", "AppGraph", "NetworkEvent", "ConsoleEvent",
    "ReproductionResult", "StepEvidence", "Evidence", "Finding", "GateResult", "VerificationResult",
    "BugReport", "ManifestBug", "RunEvent", "TestResult", "QAState",
    "CreateRunRequest", "RunMetrics", "RunSummary",
]
SCHEMA_DIR = ROOT / "packages/shared/schemas"
TS_PATH = ROOT / "packages/ui/lib/generated/contracts.ts"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        variants = schema.get("anyOf", schema.get("oneOf", []))
        return " | ".join(dict.fromkeys(ts_type(item) for item in variants))
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(dict.fromkeys(ts_type({**schema, "type": item}) for item in kind))
    if kind == "array":
        item_type = ts_type(schema.get("items", {}))
        return f"Array<{item_type}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            additional = schema.get("additionalProperties")
            return f"Record<string, {ts_type(additional)}>" if isinstance(additional, dict) else "Record<string, unknown>"
        required = set(schema.get("required", []))
        fields = [f"  {json.dumps(key)}{'?' if key not in required else ''}: {ts_type(value)};"
                  for key, value in properties.items()]
        return "{\n" + "\n".join(fields) + "\n}"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def outputs() -> dict[Path, str]:
    schemas: dict[str, dict[str, Any]] = {}
    individual: dict[Path, str] = {}
    for name in CONTRACT_NAMES:
        model = getattr(models, name)
        schema = model.model_json_schema(by_alias=True, ref_template="#/$defs/{model}")
        individual[SCHEMA_DIR / f"{name.lower()}.schema.json"] = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
        schemas[name] = schema

    definitions: dict[str, Any] = {}
    for name, schema in schemas.items():
        definitions.update(schema.get("$defs", {}))
        definitions[name] = {key: value for key, value in schema.items()
                             if key not in {"$defs", "$schema", "$id"}}
    aggregate = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://argus.local/schemas/contracts.schema.json",
        "title": "ArgusContracts",
        "oneOf": [{"$ref": f"#/$defs/{name}"} for name in CONTRACT_NAMES],
        "$defs": definitions,
    }
    individual[SCHEMA_DIR / "contracts.schema.json"] = json.dumps(aggregate, indent=2, ensure_ascii=False) + "\n"

    ts = ["/* Generated by `make schemas`; edit the Pydantic models instead. */", ""]
    for name, definition in definitions.items():
        if definition.get("type") == "object" and definition.get("properties"):
            ts.append(f"export interface {name} {ts_type(definition)}")
        else:
            ts.append(f"export type {name} = {ts_type(definition)};")
        ts.append("")
    return {**individual, TS_PATH: "\n".join(ts)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated files are stale")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"generated {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Generated contract files are stale:", *stale, sep="\n  ", file=sys.stderr)
        print("Run `make schemas` and commit the generated output.", file=sys.stderr)
        return 1
    if args.check:
        print("Generated contract files are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
